    def gen_ep_func_body(self, file, b_singleton, ct_name, global_ct_name, sig_name,
                         ep_name, func_name, func_global_name, func_type, params):
        ct = str(ct_name)
        ep = str(ep_name)
        fn = str(func_name)

        if ct == self.datapump_celltype:
            file.print(
                "    ER      ercd = E_OK;                      // DataPumpHolderPlugin 0\n"
                "    CELLCB  *p_cellcb = GET_CELLCB(idx);\n"
                "    //  variables from data definition in celltype {}\n"
                "#ifdef DATAPUMPHOLDER_DEBUG\n"
                '    syslog( LOG_INFO, "DataPumpHolderPlugin {}.{}.{}" );\n'
                "#endif\n".format(self.celltype.get_name(), ct, ep, fn))

            for decl in list(self.attr_list) + list(self.var_list):
                type_ = decl.get_type().get_original_type()
                if isinstance(type_, PtrType):
                    type_ = type_.get_type()
                if decl.get_size_is():
                    size = "[{}]".format(decl.get_size_is())
                    size_note = "    // note: if size of array is too large, stack overflow might happen here or later"
                else:
                    size = ""
                    size_note = ""
                file.print("    {}\t{}{}{};{}\n".format(
                    type_.get_type_str(),
                    decl.get_identifier(),
                    type_.get_type_str_post(),
                    size,
                    size_note))

            file.print(
                "\n"
                "    // mikan: need error check\n"
                "    cPubSide_waitForNewData();    // wait for PubSide\n"
                "    cSubSide_waitForReadDone();   // wait for SubSuide\n")
            for decl in list(self.attr_list) + list(self.var_list):
                ref = "&" if decl.get_ptr_level() == 0 else ""
                file.print(
                    "\n"
                    "    // data: {0} get & set\n"
                    "    cPubSide_get_{0}( {1}{0} );\n"
                    "    cSubSide_set_{0}( {0} );\n".format(
                        decl.get_identifier(), ref))
            file.print(
                "\n"
                "    /// mikan: need error check\n"
                "    cPubSide_dataReadDone();\n"
                "    cSubSide_newDataReady();\n"
                "\n"
                "    return ercd;\n")

        elif ct == self.dataholder_celltype:
            if ep == "eSubSide":
                if fn == "waitForNewData":
                    file.print(
                        "    // wait For PubSide New Data\n"
                        "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                        "    ER       ercd = E_OK;\n"
                        "    FLGPTN   flgptn;\n"
                        "\n"
                        "#ifdef DATAPUMPHOLDER_DEBUG\n"
                        '    syslog( LOG_INFO, "DataPumpHolderPlugin {}.{}.{}" );\n'
                        "#endif\n"
                        "    if( is_cEventflag_joined() ){{\n"
                        "      if( VAR_status != DATAHOLDER_STAT_READING ){{\n"
                        "        ercd = cEventflag_wait( DATAHOLDER_EVFLAG_NEW_DATA, TWF_ANDW, &flgptn );\n"
                        "        (void)flgptn;\n"
                        "        if( ercd == E_OK ){{\n"
                        "          VAR_status = DATAHOLDER_STAT_READING;\n"
                        "        }}\n"
                        "      }} else{{\n"
                        "       ercd = E_PAR;\n"
                        "      }}\n"
                        "    }}\n"
                        "    return ercd;\n".format(ct, ep, fn))
                elif fn == "dataReadDone":
                    file.print(
                        "    // data Read Done\n"
                        "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                        "    ER       ercd = E_OK;\n"
                        "\n"
                        "#ifdef DATAPUMPHOLDER_DEBUG\n"
                        '    syslog( LOG_INFO, "DataPumpHolderPlugin {}.{}.{}" );\n'
                        "#endif\n"
                        "    if( is_cEventflag_joined() ){{\n"
                        "      if( VAR_status == DATAHOLDER_STAT_READING ){{\n"
                        "        VAR_status = DATAHOLDER_STAT_READ_DONE;  // フラグを操作する前に変更\n"
                        "        ercd = cEventflag_clear( ~DATAHOLDER_EVFLAG_NEW_DATA );\n"
                        "        ercd = cEventflag_set( DATAHOLDER_EVFLAG_READ_DONE ); // ここで PubSide 動作開始可能\n"
                        "      }} else {{\n"
                        "        ercd = E_PAR;\n"
                        "      }}\n"
                        "    }}\n"
                        "    return ercd;\n".format(ct, ep, fn))
                else:
                    file.print("/* {}.{} */\n".format(ep, fn))
                    dat_name = re.sub(r'^get_', '', fn)
                    file.print("/* {}.{} var_name: {}*/\n".format(ep, fn, dat_name))
                    decla = self.find_decl(dat_name)
                    if decla.get_ptr_level() == 0:
                        file.print(
                            "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                            "    *{0} = VAR_{0};\n"
                            "    return E_OK;\n".format(dat_name))
                    elif decla.get_ptr_level() == 1:
                        if decla.get_size_is():
                            spec = "*{}".format(decla.get_size_is())
                        else:
                            spec = ""
                        file.print(
                            "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                            "    memcpy( {0}, VAR_{0}, sizeof(*{0}){1} );\n"
                            "    return E_OK;\n".format(dat_name, spec))
            elif ep == "ePubSide":
                if fn == "waitForReadDone":
                    file.print(
                        "    // Wait For SubSide Read-Done\n"
                        "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                        "    ER       ercd = E_OK;\n"
                        "    FLGPTN   flgptn;\n"
                        "\n"
                        "#ifdef DATAPUMPHOLDER_DEBUG\n"
                        '    syslog( LOG_INFO, "DataPumpHolderPlugin {}.{}.{}" );\n'
                        "#endif\n"
                        "    if( is_cEventflag_joined() ){{\n"
                        "      // cygwin_kernel.cdl の環境では、Eventflag の初期値が設定されないため\n"
                        "      // ここで設定する (この設定は、正規の環境で残っても問題ない)\n"
                        "      if( VAR_status == DATAHOLDER_STAT_NONE ){{\n"
                        "        VAR_status= DATAHOLDER_STAT_READ_DONE;\n"
                        "        cEventflag_set( DATAHOLDER_EVFLAG_READ_DONE );\n"
                        "      }}\n"
                        "      if( VAR_status != DATAHOLDER_STAT_WRITING ){{\n"
                        "        ercd = cEventflag_wait( DATAHOLDER_EVFLAG_READ_DONE, TWF_ANDW, &flgptn );\n"
                        "        (void)flgptn;\n"
                        "        if( ercd == E_OK ){{\n"
                        "          VAR_status = DATAHOLDER_STAT_WRITING;\n"
                        "        }}\n"
                        "      }} else{{\n"
                        "        ercd = E_PAR;\n"
                        "      }}\n"
                        "    }}\n"
                        "    return ercd;\n".format(ct, ep, fn))
                elif fn == "newDataReady":
                    file.print(
                        "    // New Data Ready\n"
                        "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                        "    ER       ercd = E_OK;\n"
                        "\n"
                        "#ifdef DATAPUMPHOLDER_DEBUG\n"
                        '    syslog( LOG_INFO, "DataPumpHolderPlugin {}.{}.{}" );\n'
                        "#endif\n"
                        "    if( is_cEventflag_joined() ){{\n"
                        "      if( VAR_status == DATAHOLDER_STAT_WRITING ){{\n"
                        "        VAR_status = DATAHOLDER_STAT_WRITE_DONE;  // フラグを操作する前に変更\n"
                        "        ercd = cEventflag_clear( ~DATAHOLDER_EVFLAG_READ_DONE );\n"
                        "        ercd = cEventflag_set( DATAHOLDER_EVFLAG_NEW_DATA ); // ここで SubSide 動作開始可能\n"
                        "      }} else{{\n"
                        "       ercd = E_PAR;\n"
                        "      }}\n"
                        "    }}\n"
                        "    return ercd;\n".format(ct, ep, fn))
                else:
                    dat_name = re.sub(r'^set_', '', fn)
                    file.print("/* {}.{} var_name: {}*/\n".format(ep, fn, dat_name))
                    decla = self.find_decl(dat_name)
                    if decla.get_ptr_level() == 0:
                        file.print(
                            "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                            "    VAR_{0} = {0};\n"
                            "    return E_OK;\n".format(dat_name))
                    elif decla.get_ptr_level() == 1:
                        if decla.get_size_is():
                            spec = "*{}".format(decla.get_size_is())
                        else:
                            spec = ""
                        file.print(
                            "    CELLCB   *p_cellcb = GET_CELLCB(idx);\n"
                            "    memcpy( VAR_{0}, {0}, sizeof(*{0}){1} );\n"
                            "    return E_OK;\n".format(dat_name, spec))
            else:
                raise Exception(
                    "DataPumpHolderPlugin: Unknown celentryltype {}.{}".format(ct, ep))

        elif ct in (self.sync_adaptor_celltype, self.async_adaptor_celltype):
            file.print("    CELLCB  *p_cellcb = GET_CELLCB(idx);\n")
            if not func_type.get_type().is_void():
                file.print("    return ")
            else:
                file.print("  ")
            file.print("cOut_{}(".format(fn))
            delim = ""
            for param in params:
                file.print("{}{}".format(delim, param.get_name()))
                delim = ", "
            file.print(");\n")
        else:
            if not G.generate_all_template:
                raise Exception("DataPumpHolderPlugin: Unknown celltyep {}".format(ct))

    def gen_preamble(self, file, b_singleton, ct_name, global_ct_name):
        ct = str(ct_name)
        if ct == self.sync_adaptor_celltype:
            file.print(
                "    /* このセルタイプは、waitForReadDone 関数を非 oneway 化するためのもの */\n")
        elif ct == self.async_adaptor_celltype:
            file.print(
                "    /* このセルタイプは、waitForReadDone 関数を oneway 化するためのもの */\n")

    def find_decl(self, var_attr_name):
        name = str(var_attr_name)
        for decl in self.attr_list:
            if str(decl.get_name()) == name:
                return decl
        for decl in self.var_list:
            if str(decl.get_name()) == name:
                return decl
        raise Exception(
            "DataPumpHolderPlugin: Unknown data name {} data:{}".format(
                self.celltype.get_name(), var_attr_name))
