    #=== Cell#restrict を追加
    def add_restrict(self, entry_name, func_name, region_name_list):
        from tecslib.core.componentobj.namespace import Namespace
        from tecslib.core.componentobj.region import Region

        if self.restrict_list.get(entry_name) is None:
            self.restrict_list[entry_name] = {}
            self.restrict_list2[entry_name] = {}
        if self.restrict_list[entry_name].get(func_name) is None:
            self.restrict_list[entry_name][func_name] = []
            self.restrict_list2[entry_name][func_name] = []
        for rp in region_name_list:
            self.restrict_list[entry_name][func_name].append(rp)
            # p "Class: " + rp.to_s
            obj = Namespace.find(rp)
            if isinstance(obj, Region):
                self.restrict_list2[entry_name][func_name].append(obj.get_domain_root())
            else:
                self.cdl_error("S9999 $1 not found or not region", str(rp))

    #=== Cell#check_restrict_list
    def check_restrict_list(self):
        from tecslib.core.componentobj.namespace import Namespace
        from tecslib.core.componentobj.region import Region

        # p "check_restrict_list"
        for entry_name, func_hash in self.restrict_list.items():
            for func_name, region_list in func_hash.items():
                for rp in region_list:
                    obj = Namespace.find(rp)
                    if isinstance(obj, Region):
                        if obj.get_domain_root() != self.region.get_domain_root():
                            pass
                        else:
                            self.cdl_info("I9999 $1: restrict calling domain to $2, which is same domain as the cell locates",
                                          self.name, str(rp))
                            # restrict を同じドメインを指定してもよいこととする (HRP3)
                            # KernelDoamin 内のセルに対し、KernelDomain に restrict している場合、
                            # 無所属経由で結合されているが、KernelDomain から呼出すことを想定した許可
                    else:
                        self.cdl_error("S9999 $1 not region", str(rp))

    #=== Cell#callable?
    def callable(self, callee_cell, entry_name, func_name):
        # p "callable? #{@name}"
        res = callee_cell.callable_from(entry_name, func_name, self)
        dbgPrint("callable? {}.{}.{} from {} is {}\n".format(
            callee_cell.get_namespace_path(), entry_name, func_name, self.NamespacePath, res))
        return res

    #=== Cell#callable_from? (private)
    def callable_from(self, entry_name, func_name, caller_cell):
        self.b_restrict_referenced = True
        if len(self.restrict_list) == 0:
            return True

        dr = caller_cell.get_region().get_domain_root()
        if self.restrict_list.get(entry_name):
            if self.restrict_list[entry_name].get(func_name):
                for region in self.restrict_list2[entry_name][func_name]:
                    if dr is region:
                        return True
            elif self.restrict_list[entry_name].get(None):
                for region in self.restrict_list2[entry_name][None]:
                    if dr is region:
                        return True
            else:
                return False
        else:
            return False

    #=== Cell#get_callable_regions( entry_name, func_name )
    # func_name=nil の場合、entry_name の可否をチェックする
    # nil が返る場合、制限されていないことを意味する
    # 返された、受け口、受け口関数へ
    def get_restricted_regions(self, entry_name, func_name):
        # p "get_restricted_regions #{@name}"
        self.b_restrict_referenced = True
        if self.restrict_list.get(entry_name):
            if self.restrict_list[entry_name].get(func_name):
                return self.restrict_list2[entry_name][func_name]
            else:
                return self.restrict_list2[entry_name].get(None)
        return None

    #=== Cell#has_ineffective_restrict_specifier
    # restrict 指定子が指定されていて、参照されていない場合 true
    # 参照は、HRPSVCPlugin のみ
    def has_ineffective_restrict_specifier(self):
        if len(self.restrict_list) != 0 and self.b_restrict_referenced is False:
            return True
        else:
            return False

