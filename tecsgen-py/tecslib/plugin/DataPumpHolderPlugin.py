class DataPumpHolderPlugin(CelltypePlugin):

    count = 0

    def __init__(self, celltype, option):
        super().__init__(celltype, option)
        self.celltype = celltype
        self.plugin_arg_str = CDLString.remove_dquote(option)
        self.plugin_arg_list = {}
        self.cell_list = []

        self.namespace_pre = celltype.get_namespace().get_global_name()
        self.signature_pre = re.sub(r'^t', 's', str(celltype.get_name()))
        self.signature_prefix = "{}_{}".format(self.namespace_pre, self.signature_pre)
        self.celltype_prefix = celltype.get_global_name()
        self.celltype_cdl_name = "{}_celltype.cdl".format(celltype.get_global_name())
        self.signature_cdl_name = "{}_signature.cdl".format(celltype.get_global_name())

        self.attr_list = celltype.get_attribute_list()
        self.var_list = celltype.get_var_list()

        signame = re.sub(r'^t', 's', str(celltype.get_name()))
        self.get_signature = "{}GetSignature".format(signame)
        self.set_signature = "{}SetSignature".format(signame)
        self.datapump_celltype = "{}DataPump".format(celltype.get_name())
        self.dataholder_celltype = "{}DataHolder".format(celltype.get_name())
        self.datapumpholder_celltype = "{}DataPumpHolder".format(celltype.get_name())
        self.set_signature_async = "{}SetSignatureAsync".format(signame)
        self.sync_adaptor_celltype = "{}SyncAdaptor".format(celltype.get_name())
        self.async_adaptor_celltype = "{}AsyncAdaptor".format(celltype.get_name())
        self.gen_get_set_signature()
        self.gen_pump_holder_celltype()

    def new_cell(self, cell):
        self.cell_list.append(cell)

