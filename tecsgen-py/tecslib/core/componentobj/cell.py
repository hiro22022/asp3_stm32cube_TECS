    #=== Cell# リレーアロケータの結合を生成
    # STAGE: S
    # 呼び口側の結合を元に受け口側の結合を生成
    def create_relay_allocator_join(self):
        from tecslib.core.componentobj.compositecelltype import CompositeCelltype
        from tecslib.core.componentobj.join import Join

        # celltype がなければチェックしない（既にエラー）
        if self.celltype is None:
            return

        # relay allocator を生成
        for p in self.celltype.get_port_list():
            ail = p.get_allocator_instance()
            if ail:
                dbgPrint("create_relay_allocator_join: {}, {}\n".format(self.name, p.get_name()))
                if p.get_array_size():
                    # mikan relay allocator が array に対応できてもよいのでは？
                    self.cdl_error("S1040 array not supported for relay allocator")
                    continue
                for name, ai2 in ail.items():
                    # ai2 = [ :INTERNAL_ALLOC|:RELAY_ALLOC, func_name, param_name, rhs_cp_name, rhs_func_name, rhs_param_name ]
                    if ai2[0] == "RELAY_ALLOC":
                        dbgPrint("create_relay_allocator_join: {}, {}\n".format(self.name, name))
                        # 呼び口側の結合を取り出す
                        ja = self.join_list.get_item(Sym("{}_{}_{}".format(ai2[3], ai2[4], ai2[5])))
                        if ja is None:
                            # 見つからない場合
                            found = False

                            # composite 内で外部に結合されているか
                            if self.in_composite:
                                for cj in self.compositecelltypejoin_list.get_items():
                                    dbgPrint("create relay_allocator in_composite\n")
                                    dbgPrint("    {} {} {} {}_{}_{}\n".format(
                                        cj.get_cell_name(), self.name, cj.get_cell_elem_name(),
                                        ai2[3], ai2[4], ai2[5]))
                                    if cj.get_cell_name() == self.name and \
                                            cj.get_cell_elem_name() == Sym("{}_{}_{}".format(ai2[3], ai2[4], ai2[5])):
                                        found = True
                                        dbgPrint("create_relay_allocator: found {}\n".format(cj.get_cell_elem_name()))
                                        break

                            if found is False:
                                self.cdl_error("S1041 \'$1_$2_$3\': not joined. cannot create internal join for relay allocator",
                                               ai2[3], ai2[4], ai2[5])
                                # print( "      In cell #{get_name}\n" )
                                # join が未結合であることのエラーは二度でる (S1043)
                            continue    # 打ち切る

                        b_export = False
                        # composite 内のセルでエクスポートされているかチェック
                        #  mikan エクスポート側と、こちら側で、リレー先が一致するかチェックが必要
                        if self.compositecelltypejoin_list:
                            # export されているか調べる
                            for cj in self.compositecelltypejoin_list.get_items():
                                # 属性名と composite の export する名前は一致するか
                                if p.get_name() == cj.get_cell_elem_name():
                                    # print "export : #{p.get_name}\n"
                                    b_export = True    # 属性は export されているので、とりあえず未初期化とはしない
                                    break
                            #

                        # mikan 配列
                        am = None
                        if am:
                            for ja2 in am:
                                rhs = ja2.get_rhs()
                                subscript = ja2.get_subscript()
                                if b_export is False:
                                    # CompositeCelltype の場合、内側のセルで生成させる
                                    join = Join(Sym("{}_{}_{}".format(p.get_name(), ai2[1], ai2[2])),
                                                subscript, rhs, self.loacle)
                                    # p ( "#{p.get_name}_#{ai2[1]}_#{ai2[2]}", subscript, rhs )
                                    self.new_join_inst(join)
                                    join.set_definition(self.celltype.find(join.get_name()))
                                    # mikan relay mismatch チェックができていない（下方を参照）
                                self.alloc_list.append(["NORMAL_ALLOC", p.get_name(), subscript, ai2[1], ai2[2], rhs])
                        else:
                            if b_export is False:
                                # CompositeCelltype の場合、内側のセルで生成させる
                                join = Join(Sym("{}_{}_{}".format(p.get_name(), ai2[1], ai2[2])),
                                            None, ja.get_rhs(), self.locale)
                                self.new_join_inst(join)
                                join.set_definition(self.celltype.find(join.get_name()))
                                if type(self.celltype) is CompositeCelltype:
                                    jr = self.join_list.get_item(Sym("{}_{}_{}".format(ai2[3], ai2[4], ai2[5])))
                                    if jr.get_rhs_cell2() != join.get_rhs_cell2() or jr.get_rhs_port2() != join.get_rhs_port2():
                                        self.cdl_error("S1167 \'$1\': relay mismatch \'$2\'",
                                                       "{}_{}_{}".format(p.get_name(), ai2[1], ai2[2]),
                                                       "{}_{}_{}".format(ai2[3], ai2[4], ai2[5]))
                                        # 本当は composite の呼び口と受け口の間で行うべきだが、内部で多段接続されている場合
                                    else:
                                        dbgPrint("relay success:  {}_{}_{}=>{}_{}_{} {}.{} \n".format(
                                            p.get_name(), ai2[1], ai2[2], ai2[3], ai2[4], ai2[5],
                                            jr.get_rhs_cell2().get_name(), jr.get_rhs_port2()))
                            self.alloc_list.append(["NORMAL_ALLOC", p.get_name(), None, ai2[1], ai2[2], ja.get_rhs()])
                        dbgPrint("create_relay_allocator_join: {}_{}_{} {}_{}_{}\n".format(
                            p.get_name(), ai2[1], ai2[2], ai2[3], ai2[4], ai2[5]))

