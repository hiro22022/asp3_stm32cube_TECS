    def clone_for_composite(self, name, global_name, namespacePath, join_array, ct_name, region, plugin, locale):
        from tecslib.core.componentobj.celltype import Celltype
        from tecslib.core.componentobj.compositecelltype import CompositeCelltype

        # debug
        dbgPrint("  CLONING Cell#clone_for_composite : cloning: {} {}  b_defined={} {}=>{} \n".format(
            self.name, global_name, self.b_defined, self, self.my_clone))
        dbgPrint("              my_name={} name={} owner class={}\n".format(
            self.name, name, self.owner.__class__.__name__))

        self.my_clone = copy.copy(self)

        # clone したセルの内部に持つ名前情報を調整する
        self.my_clone.set_cloned(name, global_name, namespacePath, join_array, ct_name, region, plugin, locale)

