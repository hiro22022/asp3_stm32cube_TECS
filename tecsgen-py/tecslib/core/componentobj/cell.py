    #=== Cell# cell の指定子を設定
    # STAGE:  B
    #
    #    bnf.y.rb の statement_specifiler_list
    #spec_list::      [ :ALLOCATOR, [ [ :NORMAL_ALLOC, ep_name, subscript, func_name, param_name, expr ], ... ] ]
    #                     s[0]      s[1]   a[0]        a[1]       a[2]        a[3]     a[4]       a[5]
    #    セルに指定されたアロケータ指定子
    #    a[1] の subscript はこのメソッドの中で Expression から Integer に評価される
    #    受け口側に生成されるアロケータ呼び口の結合を内部生成する
    #    呼び口側は Port の create_allocator_join にて生成
    #    リレーアロケータの場合 create_relay_allocator_join にて生成す
    def set_specifier_list(self, spec_list):
        from tecslib.core.componentobj.join import Join
        from tecslib.core.expression import Expression
        from tecslib.core.syntaxobj.cdlstring import CDLString

        if spec_list is None:  # 空ならば何もしない
            return

        dbgPrint("set_spec_list: {}\n".format(self.name))
        b_generate = False   # generate が指定された

        for s in spec_list:
            case = s[0]             # statement_specifier
            if case == "ALLOCATOR":       # [allocator(ePort.func.param=allocCell.eA,ePort.func2.param=allocCell.eA)]
                for a in s[1]:     # alloc_list : allocator の内部の ',' で区切られた部分の配列
                    cp_name = Sym("{}_{}_{}".format(a[0 + 1], a[2 + 1], a[3 + 1]))    # アロケータ呼び口の名前：'=' の左辺を '.' に変えて '_' で連結
                    # p "#{a[0]} #{a[0+1]} #{a[2+1]} #{a[3+1]} #{cp_name}"
                    if a[1 + 1]:
                        subscript = a[1 + 1].eval_const(None)
                        a[1 + 1] = subscript
                    else:
                        subscript = None
                    # アロケータ呼び口の結合を生成
                    join = Join(cp_name, subscript, a[4 + 1])   # 構文解析段階なので locale 不要
                    dbgPrint("new allocator join {} {} {}\n".format(cp_name, subscript, a[4 + 1]))
                    Cell.current_object.new_join_inst(join)
                    self.alloc_list.append(a)
            elif case == "ID":          # [id(0)]
                if type(s[1]) is not Expression:
                    self.cdl_error("S1160 $1 must be constant for id", str(s[1]))
                else:
                    id = s[1].eval_const(None)
                    if id is None or not isinstance(id, int):
                        self.cdl_error("S1161 $1 must be constant for id", str(s[1]))
                    elif id == 0:
                        self.cdl_error("S1162 $1: id cannot be 0", str(s[1]))
                    else:
                        self.id_specified = id
            elif case == "GENERATE":      # [generate(CellPlugin,"option")]
                if self._generate:
                    self.cdl_error("S1163 generate specifier duplicate")
                self._generate = [s[1], s[2]]  # [ PluginName, "option" ]
                b_generate = True
            elif case == "PROTOTYPE":     # [prototype]
                self.b_prototype = True
            elif case == "RESTRICT":      # [restrict]
                for re in s[1]:
                    self.add_restrict(re[0], re[1], re[2])
            elif case == "THROUGH":       # [through(ThroughPlugin,"option")]
                ep_name = Sym(str(s[1]))
                pluginName = s[2]
                option = CDLString.remove_dquote(str(s[3]))
                dbgPrint("through: celltype={} ep_name={}\n".format(self.celltype.get_name(), ep_name))
                if self.celltype.find(ep_name) is None:
                    self.cdl_error("S9999 '$1' entry port not exist", ep_name)
                self.ep_through_list.append([ep_name, pluginName, option])      # [ ep_name, pluginName, "option" ]
            else:
                self.cdl_error("S1039 \'$1\': unknown specifier for cell", s[0])
        if self.b_prototype:
            if b_generate:
                self.cdl_error("S9999 '$1': generate and prototype specified simultaneously", self.name)
            if self.b_defined:
                self.cdl_error("S9999 '$1': prototype specified after definition", self.name)

