    def end_of_parse_inst(self, f_def):
        import tecsgen
        from tecslib.core.bnf import Generator

        TECSGEN = tecsgen.TECSGEN

        if self.b_prototype:  # prototype 指定子あったか?
            f_def = False       # プロトタイプ宣言とする
            self.b_prototype = False
        if f_def is False:
            # cell tCelltype Cell; の形式の場合
            # f_def == true の場合 new_def で、呼出される
            self.set_specifier_list(Generator.get_statement_specifier())
        if TECSGEN.post_coded():
            self.b_post_code_generated = True
