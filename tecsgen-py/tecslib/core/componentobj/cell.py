        region.new_cell_inst(self)  # mikan  namespace に cell を置けないことを仮定

        # join_list : NamedList の clone を作る
        if self.celltype:
            dbgPrint("set_cloned: celltype={} name={} global_name={} region={}\n".format(
                self.celltype.get_name(), self.name, global_name, region.get_name()))
